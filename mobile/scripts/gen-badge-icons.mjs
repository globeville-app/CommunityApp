/**
 * Copies the Lucide icons the badges use (docs/BADGE_UI.md) into
 * src/components/badges/lucideData.ts, along with Lucide's ISC license for
 * the Open-source credits screen. Run after changing the lucide-static
 * version: `node scripts/gen-badge-icons.mjs`.
 *
 * We copy the drawing data instead of importing Lucide's components because
 * the badges color single parts of an icon (the yellow accents).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const mobileDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lucideDir = path.join(mobileDir, "node_modules", "lucide-static");
const ICONS = [
  // Emblems
  "house", "blend", "heart", "party-popper", "store", "sparkles", "zap", "hand-helping",
  "broom-sparkles", "megaphone", "languages", "door-open", "smile", "sun-snow",
  // Stage pips
  "bean", "sprout", "flower", "tree-pine", "trees",
];

const version = JSON.parse(fs.readFileSync(path.join(lucideDir, "package.json"), "utf8")).version;
const parts = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(lucideDir, "icons", `${name}.svg`), "utf8");
  parts[name] = [...svg.matchAll(/<(path|circle)\s([^>]*?)\/?>/g)].map(([, tag, attrs]) => {
    const values = Object.fromEntries([...attrs.matchAll(/([a-z]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]));
    return tag === "circle" ? { circle: [Number(values.cx), Number(values.cy), Number(values.r)] } : { d: values.d };
  });
}
// The ISC part only: none of the icons above are the Feather-derived ones
// the rest of the file covers.
const license = fs.readFileSync(path.join(lucideDir, "LICENSE"), "utf8").split("\n---")[0].trim();

const out = `// Generated by scripts/gen-badge-icons.mjs from lucide-static ${version}. Do not edit.
// Lucide icons, https://lucide.dev, ISC license (below).

export type IconPart = { d: string } | { circle: [number, number, number] };

export const LUCIDE_VERSION = ${JSON.stringify(version)};

export const LUCIDE_LICENSE = ${JSON.stringify(license)};

export const ICON_PARTS: Record<string, IconPart[]> = {
${Object.entries(parts)
  .map(([name, list]) => `  ${JSON.stringify(name)}: ${JSON.stringify(list)},`)
  .join("\n")}
};
`;
fs.writeFileSync(path.join(mobileDir, "src", "components", "badges", "lucideData.ts"), out);
console.log(`Wrote ${ICONS.length} icons from lucide-static ${version}`);
